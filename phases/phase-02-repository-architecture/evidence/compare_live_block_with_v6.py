#!/usr/bin/env python3
"""Compare Phase 2's live block with v6-polled, run by run, and write Markdown.

    python phases/phase-02-repository-architecture/evidence/compare_live_block_with_v6.py

The Phase 2 exit criterion is that the baseline's examples run through the new
modular structure "without changing their expected behaviour". The goldens
prove that call for call against a fake. This shows it in the simulator: the
same 30 missions, flown on 2026-10-20 by the refactored code, against the
citable Phase 1 block flown on 2026-10-19 by the code at the tag.

Matched by (mission, attempt, drone). Plans are compared exactly, as raw model
text. Outcomes -- completed, landed, collision -- must be equal. Flights cannot
be compared exactly, because the simulator is not bit-for-bit deterministic,
so each physical quantity is judged against how much v6 varied BETWEEN ITS OWN
THREE REPEATS of the same mission and drone: a difference from v6 no larger
than v6's difference from itself is the simulator's own scatter, not a change
of behaviour. A small floor stands in for noise where v6's repeats happened to
agree exactly.

Reads the results; writes only its own output, `live-block-vs-v6-2026-10-20.md`
beside this script, in UTF-8.
"""

from __future__ import annotations

import glob
import hashlib
import itertools
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
P1 = os.path.join(REPO, "phases", "phase-01-baseline-freeze", "results")
P2 = os.path.join(REPO, "phases", "phase-02-repository-architecture", "results")

V6 = [os.path.join(P1, f"baseline_v1-llama3.3_70b-20261019-{s}-v6-polled.jsonl")
      for s in ("182324", "183553", "183805")]
LIVE = {
    "plan-only": os.path.join(P2, "baseline_v1-llama3.3_70b-20261020-192150-p2-planonly.jsonl"),
    "A": os.path.join(P2, "baseline_v1-llama3.3_70b-20261020-193347-p2-blockA.jsonl"),
    "B": os.path.join(P2, "baseline_v1-llama3.3_70b-20261020-194802-p2-blockB-M09.jsonl"),
    "C": os.path.join(P2, "baseline_v1-llama3.3_70b-20261020-195048-p2-blockC-M10.jsonl"),
}
OUT = os.path.join(HERE, "live-block-vs-v6-2026-10-20.md")

# The quantities compared, and the noise floor under v6's own spread for each.
QUANTITIES = {"final_z": 0.05, "final_xy": 0.10, "step_agl": 0.10, "flight_s": 0.5}


def rows(path: str) -> list[dict]:
    with open(path, encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def measures(outcome: dict) -> dict[str, object]:
    f = outcome["final_position"]
    return {"final_z": f["z"], "final_xy": (f["x"], f["y"]),
            "step_agl": [a["agl"] for a in outcome["step_altitudes_agl"]],
            "flight_s": outcome["flight_seconds"]}


def distance(key: str, a: object, b: object) -> float:
    if key == "final_xy":
        return max(abs(a[0] - b[0]), abs(a[1] - b[1]))
    if key == "step_agl":
        assert len(a) == len(b), "different number of steps"
        return max((abs(x - y) for x, y in zip(a, b)), default=0.0)
    return abs(a - b)


def package_digest_of(folder: str) -> str:
    """agentic_uav digest of a code snapshot, as provenance.package_digest computes it."""
    paths = sorted(glob.glob(os.path.join(folder, "agentic_uav", "**", "*.py"), recursive=True))
    digest = hashlib.sha256()
    for path in paths:
        digest.update(os.path.relpath(path, folder).replace(os.sep, "/").encode() + b"\0")
        with open(path, "rb") as handle:
            digest.update(handle.read() + b"\0")
    return digest.hexdigest()[:16]


def main() -> None:
    v6_rows = [r for p in V6 for r in rows(p)]
    v6 = {(r["mission"], r["attempt"]): r for r in v6_rows}

    # v6's own spread, per (mission, drone, quantity), over its three repeats.
    repeats: dict[tuple[str, str], list[dict]] = {}
    for r in v6_rows:
        for o in r["execution"]["outcomes"]:
            repeats.setdefault((r["mission"], o["drone"]), []).append(measures(o))
    spread = {(k, q): max(distance(q, a[q], b[q]) for a, b in itertools.combinations(ms, 2))
              for k, ms in repeats.items() for q in QUANTITIES}

    out = ["# Phase 2 live block against `v6-polled`", "",
           "Generated by `compare_live_block_with_v6.py` beside this file, which says how. Reads the "
           "four Phase 2 result files of 2026-10-20 and the three `v6-polled` files of 2026-10-19.", ""]

    # ---------------------------------------------------------------- which code
    out += ["## Which code flew", "",
            "| Session | Commit | `agentic_uav` digest in the manifest | Snapshot re-hashed |",
            "|---|---|---|---|"]
    digests = set()
    for label, path in LIVE.items():
        stem = os.path.splitext(path)[0]
        with open(os.path.join(stem + "-code", "manifest.json"), encoding="utf-8") as handle:
            manifest = json.load(handle)
        recomputed = package_digest_of(stem + "-code")
        digests.add(manifest["agentic_uav_sha256"])
        out.append(f"| {label} | `{manifest['commit']}` | `{manifest['agentic_uav_sha256']}` | "
                   f"`{recomputed}` {'(matches)' if recomputed == manifest['agentic_uav_sha256'] else '(DIFFERS)'} |")
    out += ["", f"One package digest across all four sessions: **{'yes' if len(digests) == 1 else 'NO'}**. "
            "Each manifest says `dirty: true` only because the runner writes its snapshot into "
            "the results folder before reading `git status`; see the phase record.", ""]

    # ---------------------------------------------------------------- planning
    out += ["## Planning — every drone-plan, as raw model text", "",
            "| Session | Runs | Drone-plans | Raw text identical to v6 | Plan identical | Valid | Scored correct |",
            "|---|---|---|---|---|---|---|"]
    for label, path in LIVE.items():
        rs = rows(path)
        plans = raw = same_plan = 0
        for r in rs:
            ref = {d["drone"]: d for d in v6[(r["mission"], r["attempt"])]["per_drone"]}
            for d in r["per_drone"]:
                plans += 1
                raw += d["raw_output"] == ref[d["drone"]]["raw_output"]
                same_plan += d["plan_steps"] == ref[d["drone"]]["plan_steps"]
        scored = [r for r in rs if r["scoreable"]]
        out.append(f"| {label} | {len(rs)} | {plans} | {raw}/{plans} | {same_plan}/{plans} | "
                   f"{sum(r['all_valid'] for r in rs)}/{len(rs)} | "
                   f"{sum(r['all_correct'] for r in scored)}/{len(scored)} |")
    out.append("")

    # ---------------------------------------------------------------- flight
    out += ["## Flight — the 30 flown runs, drone by drone", "",
            "Each cell is this run's difference from the same run in v6, then in brackets "
            "the most v6 differed from itself across its three repeats of that mission and "
            "drone. A difference is within when it is no larger than v6's own spread, or "
            f"than the noise floor (final z {QUANTITIES['final_z']} m, final x/y "
            f"{QUANTITIES['final_xy']} m, step height {QUANTITIES['step_agl']} m, flight "
            f"{QUANTITIES['flight_s']} s).", "",
            "| Run | Drone | Completed · landed · collision, same as v6 | Δ final z | Δ final x/y | Δ height after each step | Δ flight s | Within |",
            "|---|---|---|---|---|---|---|---|"]
    flown = [r for label in ("A", "B", "C") for r in rows(LIVE[label])]
    outside: list[str] = []
    drone_flights = within_all = outcome_same = 0
    worst: dict[str, tuple[float, float]] = {q: (0.0, 0.0) for q in QUANTITIES}
    for r in flown:
        ref = v6[(r["mission"], r["attempt"])]
        e, re_ = r["execution"], ref["execution"]
        ref_o = {o["drone"]: o for o in re_["outcomes"]}
        same_run = e["completed"] == re_["completed"] and e["collision"] == re_["collision"]
        for o in sorted(e["outcomes"], key=lambda o: o["drone"]):
            ro = ref_o[o["drone"]]
            drone_flights += 1
            same = same_run and o["landed_on_ground"] == ro["landed_on_ground"] and o["completed"] == ro["completed"]
            outcome_same += same
            now, then = measures(o), measures(ro)
            cells, ok = [], same
            for q, floor in QUANTITIES.items():
                d = distance(q, now[q], then[q])
                allowed = max(spread[((r["mission"], o["drone"]), q)], floor)
                ok = ok and d <= allowed + 1e-9
                cells.append(f"{d:.2f} ({spread[((r['mission'], o['drone']), q)]:.2f})")
                if d - allowed > worst[q][0] - worst[q][1]:
                    worst[q] = (d, allowed)
            within_all += ok
            if not ok:
                steps = " · ".join(f"after {a['after']}: {a['agl']} (v6 {b['agl']})"
                                   for a, b in zip(o["step_altitudes_agl"], ro["step_altitudes_agl"]))
                outside.append(f"| {r['mission']} {r['attempt']}/3 | {o['drone']} | {steps} |")
            out.append(f"| {r['mission']} {r['attempt']}/3 | {o['drone']} | {'yes' if same else 'NO'} | "
                       + " | ".join(cells) + f" | {'yes' if ok else 'NO'} |")

    if outside:
        out += ["", "## Where the flights outside v6's spread differ", "",
                "Height above ground after each step, metres, this run (v6's same run). Steps "
                "before the deviation match v6 to the centimetre; the difference begins at the "
                "step in which the drones touch.", "",
                "| Run | Drone | Height after each step |", "|---|---|---|"] + outside

    sep_rows = [(r, v6[(r["mission"], r["attempt"])]) for r in flown
                if r["execution"]["separation"].get("min_separation_m") is not None]
    out += ["", "## Separation and contacts, multi-drone runs", "",
            "| Run | Min separation m (v6) | Drone–drone contacts (v6) | Deepest penetration m (v6) |",
            "|---|---|---|---|"]
    for r, ref in sep_rows:
        s, rs_ = r["execution"]["separation"], ref["execution"]["separation"]
        pen = max((c["max_penetration_depth"] for c in s["drone_collisions"]), default=0.0)
        rpen = max((c["max_penetration_depth"] for c in rs_["drone_collisions"]), default=0.0)
        pairs = sorted({tuple(sorted((c["drone"], c["object"]))) for c in s["drone_collisions"]})
        rpairs = sorted({tuple(sorted((c["drone"], c["object"]))) for c in rs_["drone_collisions"]})
        out.append(f"| {r['mission']} {r['attempt']}/3 | {s['min_separation_m']} ({rs_['min_separation_m']}) | "
                   f"{', '.join('–'.join(p) for p in pairs) or 'none'} "
                   f"({', '.join('–'.join(p) for p in rpairs) or 'none'}) | {pen} ({rpen}) |")

    out += ["", "## Verdict", "",
            f"* Plans: every drone-plan's raw text identical to v6, in all four sessions (tables above).",
            f"* Outcomes equal to v6 for **{outcome_same}/{drone_flights}** drone-flights "
            f"over {len(flown)} runs: every one completed and landed, as in v6; no run "
            "recorded a collision, as in v6.",
            f"* Physical quantities within v6's own repeat-to-repeat spread (or the noise floor) for "
            f"**{within_all}/{drone_flights}** drone-flights.",
            "* M10's Drone1–Drone3 contact, and Drone3 climbing past its 18 m to ~33 m during its "
            "`fly_backward` leg, occur in every run of both blocks: baseline behaviour, carried "
            "over unchanged, and the reason M10's Drone1 and Drone3 have the widest spread in v6 "
            "itself. Still the open investigation recorded in Phase 1.", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
